def esc(s):
    return html.escape(s, quote=False)

def link_docs(s):
    # упоминания файлов политики и согласия — ссылками
    s = s.replace(f'({esc(CONSENT)})', f'(<a href="{CONSENT}" class="text-link">открыть</a>)')
    s = s.replace(f'({esc(POLICY)})', f'(<a href="{POLICY}" class="text-link">открыть</a>)')
    s = s.replace(f'странице {esc(POLICY)}', f'странице <a href="{POLICY}" class="text-link">«Политика обработки персональных данных»</a>')
    s = s.replace(esc(OP['email']), f'<a href="mailto:{OP["email"]}" class="text-link">{OP["email"]}</a>')
    return s

def body(title, intro, sections, other):
    parts = []
    for i, (h, paras) in enumerate(sections, 1):
        inner = []
        for p in paras:
            if isinstance(p, list):
                inner.append('<ul class="legal__list">' + ''.join(f'<li>{link_docs(esc(x))}</li>' for x in p) + '</ul>')
            else:
                inner.append(f'<p class="legal__text">{link_docs(esc(p))}</p>')
        parts.append(f'<section class="legal__section"><h2 class="legal__title">{i}. {esc(h)}</h2>{"".join(inner)}</section>')
    intro_html = f'<p class="legal__text legal__lead">{link_docs(esc(intro))}</p>' if intro else ''
    return f'''<div class="wrap page legal">
<div class="eyebrow">Персональные данные</div>
<h1 class="page__title page__title--compact">{esc(title)}</h1>
<p class="legal__edition">Редакция от {EDITION}</p>
{intro_html}
{chr(10).join(parts)}
<p class="legal__text legal__other">См. также: <a href="{other[0]}" class="text-link">{esc(other[1])}</a>.</p>
</div>

'''

